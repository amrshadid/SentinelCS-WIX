// Builds src/public/custom-elements/sentinel-header.js and sentinel-footer.js from the design files.
//   design/header-footer.html   the approved header and footer study (markup and CSS)
//   design/assets/*.svg         the logos, inlined so the elements need no hosting
//   tools/sentinel-element.class.js   the behaviour
// Wix loads each custom element file on its own, so every element is one self-contained file.
// Run:  npm run build

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(join(root, path), 'utf8');
const html = read('design/header-footer.html');

const between = (pattern, label) => {
  const match = html.match(pattern);
  if (!match) throw new Error(`design/header-footer.html: ${label} not found`);
  return match[0];
};

const inlineLogos = (markup) =>
  markup.replace(/src="assets\/([a-z-]+\.svg)"/g, (_, file) => {
    const encoded = readFileSync(join(root, 'design/assets', file)).toString('base64');
    return `src="data:image/svg+xml;base64,${encoded}"`;
  });

// Page-level selectors become shadow-DOM selectors.
const style = between(/<style>([\s\S]*?)<\/style>/, 'style block')
  .replace(/^<style>|<\/style>$/g, '')
  .replaceAll(':root{', ':host{')
  .replaceAll('body.dark{', '.shell.dark{')
  .replaceAll('body{', '.shell{');

const header = inlineLogos(between(/<header[\s\S]*?<\/header>/, 'header'));
const footer = inlineLogos(between(/<footer[\s\S]*?<\/footer>/, 'footer'))
  // The year is written by the element so it never goes stale.
  .replace(/© \d{4} /, '© <span class="year"></span> ');

const banner = `// GENERATED by tools/build-sentinel-elements.mjs from design/ and tools/sentinel-element.class.js.
// Edit those files and run \`npm run build\`; changes made here are overwritten.
`;

// Each file is wrapped in a function so it can be loaded more than once on a page (Wix may load it
// per placed element) without "already declared" errors, and without adding globals.
const build = (tag, template) =>
  [
    banner,
    '(() => {',
    `const TAG=${JSON.stringify(tag)};`,
    `const STYLE=${JSON.stringify(style)};`,
    `const TEMPLATE=${JSON.stringify(template)};`,
    '',
    read('tools/sentinel-element.class.js'),
    "if (!customElements.get(TAG)) customElements.define(TAG, class extends SentinelElement {});",
    "console.info(`SENTINEL: <${TAG}> loaded`);",
    '})();',
    '',
  ].join('\n');

const write = (name, text) => {
  writeFileSync(join(root, 'src/public/custom-elements', name), text);
  console.log(`${name} written (${Math.round(text.length / 1024)} KB)`);
};

write('sentinel-header.js', build('sentinel-header', header));
write('sentinel-footer.js', build('sentinel-footer', footer));
